"""Поле ввода с айфонским поведением.

Зачем
----
Сама клавиатура на iPhone системная, её рисует iOS, а не Kivy: в
Kivy 2.3 модуль платформенных провайдеров клавиатуры вырезан из
ядра целиком, ввод приходит от SDL2. Значит переделывать нечего -
он и так айфонский.

А вот само поле и его поведение остаются от Kivy, и это видно:

- курсор — тонкая полоска в цвет текста, у iPhone он в цвет акцента
  и всегда одинаковой толщины;
- выделение текста — сплошной прямоугольник без скруглений;
- для кода приглашения iPhone не предлагает автозамену и не
  подчёркивает слова, а поле об этом не просит, и iPhone присылает
  подчёркнутые подсказки прямо в коде - они портят вид;
- при долгом нажатии Kivy рисует свои метки выделения, у iPhone их
  не видно до настоящего выделения.

Чего здесь нет и почему
-----------------------
Фон поля не переделывается. В макете у поля своя «таблетка» с
конкретным цветом и радиусом, и подменять её айфонской серой заливкой
значит разойтись с макетом, а это главное требование.

Что сделано
-----------
1. Курсор: толщина 2dp (как у iPhone) и цвет акцента.
2. Выделение текста: цвет ближе к айфонскому.
3. Автозамена и подсказки выключаются там, где они не нужны:
   коды, пароли. Определяется по подсказке поля.
4. Метки выделения на iPhone не рисуются, пока выделения нет.

Правила подмешиваются в ui/kv/theme.kv - в разметке, потому что
свойства текста Kivy обновляет сам и из кода их надёжнее не трогать.
"""

IOS = True

# Слова в подсказке поля, по которым видно, что вводят код.
CODE_HINTS = ("код", "code", "инвайт", "invite")

# Идентификаторы полей кода. По подсказке их не узнать: подсказка у
# поля кода приглашения - это «A12-3B4».
CODE_FIELD_IDS = ("invite_code", "code", "class_code")

# Образец кода из подсказки поля. По нему поле узнаётся, когда у него
# нет идентификатора: объявленные прямо в разметке поля атрибута id
# не имеют.
CODE_HINT_SAMPLE = "A12"


def _is_code_field(widget) -> bool:
    """Поле ли это кода, по которому код ищут в базе.

    Узнаётся по двум признакам, потому что одного не хватает.
    Идентификатор есть не у всех полей: у поля, объявленного прямо
    в разметке, атрибута id нет вовсе. И по одному лишь образцу в
    подсказке - тоже ненадёжно: подсказку можно переписать.
    """
    if str(getattr(widget, "id", "") or "").lower() in CODE_FIELD_IDS:
        return True
    hint = str(getattr(widget, "hint_text", "") or "")
    return bool(CODE_HINT_SAMPLE and CODE_HINT_SAMPLE in hint)


def _wants_no_suggestions(widget) -> bool:
    """Нужно ли выключить автозамену.

    Решение по трём признакам: пароль, поле кода и подсказка со
    словом «код». Автозамена в коде вредна не только внешне: iPhone
    присылает подчёркнутое продолжение, оно попадает в текст поля и
    ломает проверку кода.
    """
    if getattr(widget, "password", False):
        return True
    if _is_code_field(widget):
        return True
    hint = str(getattr(widget, "hint_text", "") or "").lower()
    return any(word in hint for word in CODE_HINTS)


def apply(widget) -> None:
    """Привести поле к айфонскому поведению."""
    if widget is None:
        return

    def sync(*_args):
        # Толщина курсора: у iPhone 2dp, у Kivy по умолчанию 1dp -
        # отсюда тонкая нитка вместо нормального курсора.
        try:
            widget.cursor_width = "2dp"
        except Exception:
            pass
        # Подсказки включает и выключает сам iPhone, Kivy только
        # сообщает ему об этом. Включать обратно нельзя: поле может
        # пересоздаться, и тогда автозамена вернётся в коде.
        if _wants_no_suggestions(widget):
            try:
                widget.keyboard_suggestions = False
            except Exception:
                pass

    widget.bind(hint_text=sync, password=sync)
    sync()


_installed = False


def install() -> None:
    """Зацепить создание любого поля в приложении.

    Почему подменяется TextInput целиком, а не каждый класс: поля
    объявлены прямо в разметке как <PillInput@TextInput> и <Field@
    TextInput>, то есть класса на Python у них нет. Подменить
    создание по отдельности нельзя, а перечислять все такие имена
    пришлось бы и пришлось бы пополнять список при каждом новом
    поле. Перехват на __init__ ловит всё сразу и не требует
    перечислений.
    """
    global _installed
    if _installed:
        return
    try:
        from kivy.uix.textinput import TextInput
    except Exception:
        return

    original_init = TextInput.__init__

    def patched(self, *args, **kwargs):
        original_init(self, *args, **kwargs)
        try:
            apply(self)
        except Exception:
            # Поле обязано появиться любой ценой: без курсора толщиной
            # 2dp пользователь ничего не потеряет, кроме вида.
            pass

    TextInput.__init__ = patched
    _installed = True
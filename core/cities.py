def _normalize(text: str) -> str:
    """Приводит к виду для сравнения: без пробелов, в нижнем регистре, ё->е."""
    return (text or "").replace("ё", "е").replace("Ё", "Е").strip().lower()


# Порядок в подсказках задаётся один раз: сначала популярные города,
# потом остальные по алфавиту. Поэтому CITIES сортируется при загрузке,
# а не «как попало» в исходнике.
POPULAR = (
    "Москва", "Санкт-Петербург", "Новосибирск", "Екатеринбург", "Казань",
    "Нижний Новгород", "Челябинск", "Красноярск", "Самара", "Уфа",
    "Ростов-на-Дону", "Омск", "Воронеж", "Пермь", "Волгоград", "Краснодар",
)


def _sorted_cities():
    return tuple(sorted(CITIES, key=_normalize))


ALL_CITIES = _sorted_cities()


def search(query: str, limit: int = 6):
    """Города, подходящие под ввод. Пустой ввод — популярные города.

    Сначала идут города, которые начинаются с введённого слова, потом
    те, где слово встречается внутри («Нов» -> Новосибирск, Новомосковск).
    """
    needle = _normalize(query)
    if not needle:
        return list(POPULAR[:limit])

    starts, inside = [], []
    for city in ALL_CITIES:
        norm = _normalize(city)
        if norm.startswith(needle):
            starts.append(city)
        elif needle in norm:
            inside.append(city)
    return (starts + inside)[:limit]


def complete(query: str):
    """Подсказка целиком: если ввод — начало города, возвращаем полное имя.

    Нужна, чтобы по Enter дописывалось «Москва», а не оставалось «Мос».
    """
    needle = _normalize(query)
    if len(needle) < 2:
        return query
    for city in ALL_CITIES:
        if _normalize(city).startswith(needle):
            return city
    return query

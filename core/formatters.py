# -*- coding: utf-8 -*-
"""Форматирование того, что человек вводит в поля.

Правила простые и сделаны так, чтобы человеку не приходилось ничего
набирать руками:

  * код приглашения класса — 6 символов (A–Z + цифры), тире само
    (A12-B34);
  * код подтверждения — только заглавными буквами, без разделителей
    (123ABC);
  * имя и фамилия — только буквы, пробел, дефис и апостроф: цифры
    в имени не бывает, поэтому убираем их сразу при вводе;
  * почта и телефон — не трогаем совсем: в адресе почты регистр важен,
    а лишнее тире ломает адрес.

Тире не нарастает: если в код вставили готовое значение с дефисом,
дубликатов не будет.
"""
import re

from core import cities

# Всё, что не похоже на букву, пробел, дефис или апостроф, — лишнее.
_NAME_JUNK = re.compile(r"[^A-Za-zА-Яа-яЁё\s\-']")


def invite_format(text: str) -> str:
    """Код класса: латиница + цифры, макс. 6, тире A12-B34."""
    chars = "".join(
        ch
        for ch in (text or "").upper()
        if ("A" <= ch <= "Z") or ch.isdigit()
    )[:6]
    if len(chars) > 3:
        return chars[:3] + "-" + chars[3:]
    return chars


def code_format(text: str) -> str:
    """Код подтверждения: заглавными буквами, без тире и пробелов.

    Лишние разделители убираем: код могли вставить из буфера обмена
    уже с дефисом, а в базе он хранится шестью цифрами подряд.
    """
    joined = "".join(ch for ch in (text or "").upper() if not ch.isspace())
    return "".join(part for part in joined.split("-") if part)


def name_only(text: str) -> str:
    """Имя и фамилия: буквы, пробел, дефис, апостроф — и всё.

    Цифры и прочая «на клавиатуре подвернулась» выкидываем сразу при
    вводе, чтобы человек ничего не исправлял вручную:
    «Иван2ов» -> «Иванов», «Петров-Водкин» без изменений.
    """
    return _NAME_JUNK.sub("", text or "")


def city_complete(text: str) -> str:
    """Дописывает город до полного названия: «Мос» -> «Москва»."""
    return cities.complete(text)


def city_suggestions(text: str, limit: int = 5):
    """Список городов для показа под полем ввода."""
    return cities.search(text, limit=limit)
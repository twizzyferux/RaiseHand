"""Форматирование того, что человек вводит в поля.

Правила простые и сделаны так, чтобы человеку не приходилось ничего
набирать руками:

  * код приглашения — всегда заглавными буквами;
  * телефон или почта — тоже заглавными, и между 3-м и 4-м символом
    само подставляется тире (как в номере «916-348-25-33»).

Тире не нарастает: если пользователь вставил готовый номер с дефисами
или расставил их руками, лишние разделители не дублируются.
"""
from core import cities


def uppercase(text: str) -> str:
    """Код приглашения: все буквы заглавные."""
    return (text or "").upper()


def contact_format(text: str) -> str:
    """Почта или телефон: заглавные буквы + тире между 3-м и 4-м символом.

Как в номерах вида «916-348-25-33»: набираешь 9163 — получаешь
«916-3», дальше просто дописываешь. Дальше тире не добавляются,
чтобы адрес почты не превращался в «IVA-N@EXAMPLE.COM» дважды.

Лишние тире не накапливаются: если пользователь вставил готовый
номер с дефисами или расставил их руками, дубликатов не будет.
"""
    raw = (text or "").upper()

    # Убираем уже стоящие тире, чтобы не плодить «9-1-6-3».
    joined = "".join(part for part in raw.split("-") if part)

    if len(joined) > 3:
        return joined[:3] + "-" + joined[3:]
    return joined


def city_complete(text: str) -> str:
    """Дописывает город до полного названия: «Мос» -> «Москва»."""
    return cities.complete(text)


def city_suggestions(text: str, limit: int = 5):
    """Список городов для показа под полем ввода."""
    return cities.search(text, limit=limit)

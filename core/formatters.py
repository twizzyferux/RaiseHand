# -*- coding: utf-8 -*-
"""Форматирование того, что человек вводит в поля.

Правила простые и сделаны так, чтобы человеку не приходилось ничего
набирать руками:

  * код приглашения — всегда заглавными буквами;
  * почта или телефон — тоже заглавными, но без разделителей: в адресе
    почты лишнее тире ломает сам адрес;
  * код подтверждения — заглавными и с тире между 3-м и 4-м символом,
    как в коде «123-456».

Тире не нарастает: если в код вставили готовое значение с дефисом,
дубликатов не будет.
"""
from core import cities


def uppercase(text: str) -> str:
    """Заглавные буквы — для кода приглашения."""
    return (text or "").upper()


def contact_format(text: str) -> str:
    """Почта или телефон: только заглавные буквы.

    Тире здесь ставить нельзя: «ivan@example.com» превратится в
    «iva-n@example.com» и адрес перестанет существовать.
    """
    return (text or "").upper()


def code_format(text: str) -> str:
    """Код подтверждения: заглавные буквы + тире между 3-м и 4-м символом.

    Набираешь 1234 — получаешь «123-4», дальше просто дописываешь.
    Уже стоящие тире убираются, чтобы не плодить «12-3--4».
    """
    joined = "".join(part for part in (text or "").upper().split("-") if part)
    if len(joined) > 3:
        return joined[:3] + "-" + joined[3:]
    return joined


def city_complete(text: str) -> str:
    """Дописывает город до полного названия: «Мос» -> «Москва»."""
    return cities.complete(text)


def city_suggestions(text: str, limit: int = 5):
    """Список городов для показа под полем ввода."""
    return cities.search(text, limit=limit)

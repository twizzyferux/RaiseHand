"""Форматирование того, что человек вводит в поля.

Правила простые и сделаны так, чтобы человеку не приходилось ничего
набирать руками:

  * код приглашения — в том регистре, в котором набирают, но тире
    между 3-м и 4-м символом ставится само (А12-3Б4);
  * код подтверждения — заглавными буквами и тоже с тире после 3-го
    символа (123-456);
  * почта и телефон — не трогаем совсем: в адресе почты регистр важен,
    а лишнее тире ломает адрес.

Тире не нарастает: если в код вставили готовое значение с дефисом,
дубликатов не будет.
"""
from core import cities


def _with_dash(text: str) -> str:
    """Тире между 3-м и 4-м символом. Регистр не трогаем."""
    joined = "".join(part for part in (text or "").split("-") if part)
    if len(joined) > 3:
        return joined[:3] + "-" + joined[3:]
    return joined


def invite_format(text: str) -> str:
    """Код приглашения: как набирают + автоматическое тире."""
    return _with_dash(text)


def code_format(text: str) -> str:
    """Код подтверждения: заглавные буквы + тире после 3-го символа."""
    return _with_dash((text or "").upper())


def city_complete(text: str) -> str:
    """Дописывает город до полного названия: «Мос» -> «Москва»."""
    return cities.complete(text)


def city_suggestions(text: str, limit: int = 5):
    """Список городов для показа под полем ввода."""
    return cities.search(text, limit=limit)
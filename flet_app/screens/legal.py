def build_legal(page: ft.Page) -> ft.Control:
    back = STATE.draft.get("_legal_back") or "/welcome"

    def _close(_=None):
        STATE.go(str(back))

    blocks: list[ft.Control] = [
        ft.Text(
            "Пользовательское соглашение и политика данных",
            size=26,
            weight=ft.FontWeight.BOLD,
            color=theme.INK,
            font_family=theme.FONT_FAMILY,
        ),
        ft.Container(height=6),
        ft.Text(
            f"RaiseHand · редакция {TERMS_VERSION}",
            size=15,
            color=theme.MUTED,
            font_family=theme.FONT_FAMILY,
        ),
        ft.Container(height=8),
        ft.Text(
            "Прочитайте перед регистрацией. Нажатие «Далее» означает согласие с этим текстом.",
            size=16,
            color=theme.INK,
            font_family=theme.FONT_FAMILY,
        ),
        ft.Container(height=16),
    ]
    for title, paragraphs in _SECTIONS:
        blocks.append(
            ft.Text(
                title,
                size=18,
                weight=ft.FontWeight.W_700,
                color=theme.INK,
                font_family=theme.FONT_FAMILY,
            )
        )
        blocks.append(ft.Container(height=8))
        for paragraph in paragraphs:
            blocks.append(
                ft.Text(
                    paragraph,
                    size=16,
                    color=theme.INK,
                    font_family=theme.FONT_FAMILY,
                )
            )
            blocks.append(ft.Container(height=10))
        blocks.append(ft.Container(height=8))
    blocks.append(ft.Container(height=28))

    btn = liquid_glass.glass_circle_button(
        _close,
        content=ft.Icon(ft.Icons.ARROW_BACK, size=20, color=theme.INK),
        size=36,
        variant="white",
    )
    header = ft.Container(
        padding=ft.Padding.only(left=4, right=12, top=4, bottom=8),
        content=ft.Row(
            vertical_alignment=ft.CrossAxisAlignment.CENTER,
            controls=[
                btn,
                ft.Text(
                    "Правила",
                    size=17,
                    weight=ft.FontWeight.W_600,
                    color=theme.INK,
                    font_family=theme.FONT_FAMILY,
                ),
            ],
        ),
    )
    return ft.Column(
        expand=True,
        spacing=0,
        controls=[
            header,
            ft.Column(
                expand=True,
                scroll=ft.ScrollMode.AUTO,
                spacing=0,
                controls=[
                    ft.Container(
                        padding=ft.Padding.symmetric(horizontal=20),
                        content=ft.Column(spacing=0, controls=blocks),
                    )
                ],
            ),
        ],
    )
